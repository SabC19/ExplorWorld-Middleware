package com.sabic.explorworld.model;

public class Provincia {

	public Provincia() {
	}
	
	public Long id = null;
	public String nombre = null;

	public Long getId() {
		return id;
	}

	public void setId(Long id) {
		this.id = id;
	}

	public String getNombre() {
		return nombre;
	}

	public void setNombre(String nombre) {
		this.nombre = nombre;
	}

}
